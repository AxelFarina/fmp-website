import { products, productCats, catOrder } from './content/products.js'

/* Build the products dropdown structure for a language. */
function prodMenu(lang) {
  return catOrder.map((cat) => ({
    cat: productCats[lang][cat],
    items: Object.entries(products)
      .filter(([, p]) => p.cat === cat)
      .map(([slug, p]) => ({ slug, label: p[lang].name })),
  }))
}

